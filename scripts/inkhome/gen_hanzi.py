#!/usr/bin/env python3
"""Generates src/inkhome/mandarin/HanziData.h: the HSK1 word list (from the
Mandarin90 app's hsk1.json) with each headword character pre-rendered as a
48x48 1-bit bitmap from Noto Sans SC (SIL Open Font License 1.1).

  uv run --with pillow scripts/inkhome/gen_hanzi.py <hsk1.json> <NotoSansSC.ttf>
"""
import json
import sys

from PIL import Image, ImageDraw, ImageFont

SIZE = 48
ROW_BYTES = SIZE // 8


def render(font, ch):
    img = Image.new("1", (SIZE, SIZE), 0)
    draw = ImageDraw.Draw(img)
    l, t, r, b = draw.textbbox((0, 0), ch, font=font)
    draw.text(((SIZE - (r - l)) / 2 - l, (SIZE - (b - t)) / 2 - t), ch, font=font, fill=1)
    out = []
    for y in range(SIZE):
        for xb in range(ROW_BYTES):
            v = 0
            for bit in range(8):
                if img.getpixel((xb * 8 + bit, y)):
                    v |= 0x80 >> bit
            out.append(v)
    return out


def c_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    words = json.load(open(sys.argv[1], encoding="utf-8"))
    font = ImageFont.truetype(sys.argv[2], int(SIZE * 0.9))
    try:
        font.set_variation_by_name("Medium")
    except Exception:
        pass
    chars = []
    for w in words:
        for ch in w["simplified"]:
            if ch not in chars:
                chars.append(ch)
    lines = [
        "#pragma once",
        "",
        "// GENERATED by scripts/inkhome/gen_hanzi.py; do not edit by hand.",
        "// HSK1 words from the Mandarin90 app; characters drawn from Noto Sans SC",
        "// (Copyright Adobe, SIL Open Font License 1.1) as 48x48 1-bit bitmaps.",
        "",
        "#include <cstdint>",
        "",
        "namespace inkhome::mandarin {",
        "",
        f"constexpr int GLYPH_SIZE = {SIZE};",
        f"constexpr int GLYPH_COUNT = {len(chars)};",
        "",
        "struct Word {",
        "  const char* hanzi;",
        "  const char* pinyin;",
        "  const char* english;",
        "  uint16_t glyphs[4];  // indexes into GLYPHS; 0xFFFF ends a shorter word",
        "};",
        "",
        "constexpr Word WORDS[] = {",
    ]
    for w in words:
        idx = [chars.index(ch) for ch in w["simplified"]][:4]
        idx += [0xFFFF] * (4 - len(idx))
        lines.append(
            f"    {{{c_str(w['simplified'])}, {c_str(w['pinyin'])}, {c_str(w['english'])}, "
            f"{{{', '.join(str(i) for i in idx)}}}}},"
        )
    lines += ["};", "", f"constexpr uint8_t GLYPHS[{len(chars)}][{SIZE * ROW_BYTES}] = {{"]
    for ch in chars:
        data = render(font, ch)
        lines.append(f"    // U+{ord(ch):04X}")
        lines.append("    {" + ", ".join(f"0x{b:02x}" for b in data) + "},")
    lines += ["};", "", "}  // namespace inkhome::mandarin", ""]
    open("src/inkhome/mandarin/HanziData.h", "w", encoding="utf-8").write("\n".join(lines))
    print(f"{len(words)} words, {len(chars)} glyphs, {len(chars) * SIZE * ROW_BYTES} bitmap bytes")


main()
